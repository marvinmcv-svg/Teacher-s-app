// Regenerates lib/db/database.types.ts from the local Supabase schema.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
const types = execSync("npx -y supabase@latest gen types typescript --local", {
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});
writeFileSync(
  "lib/db/database.types.ts",
  `// Generated by \`pnpm db:types\` (supabase gen types --local). Do not edit by hand.\n${types}`,
);
execSync("npx prettier --write lib/db/database.types.ts", { stdio: "ignore" });
console.log("lib/db/database.types.ts updated");
